def classify(measured: float, bar: float, iid: float, emp: float, n: int) -> str:
    """A pass is a pass. A miss is classed by TWO independent facts, both reported when both hold:
    (1) «bar above its empirical ceiling»: the EMPIRICAL (block-bootstrap) ceiling is below the bar — the law's iid arithmetic was the defect, whatever the mechanism does;
    (2) «BELOW the empirical ceiling»: the reading is more than 2 binomial SE under the empirical ceiling — the mechanism (a hard screen's feedback trap) costs more than the clustering alone.
    If neither: the reading is inside the empirical ceiling's reach (sampling noise)."""
    if measured >= bar - 1e-12:
        return "passes"
    se = math.sqrt(max(measured * (1.0 - measured), 1e-9) / max(1, n))
    parts: List[str] = []
    if emp < bar - 1e-12:
        parts.append(f"bar above its empirical ceiling ({emp:.3f} < {bar:.2f}; iid ceiling {iid:.3f}): the law's iid arithmetic")
    if measured < emp - 2.0 * se:
        parts.append(f"BELOW the empirical ceiling ({measured:.3f} < {emp:.3f} - 2 SE {2 * se:.3f}): mechanism (the hard screen's feedback trap)")
    return "; ".join(parts) if parts else f"inside the empirical ceiling's reach ({measured:.3f} vs {emp:.3f}, 2 SE {2 * se:.3f}): sampling noise"


def _row(ceil_rows: Sequence[Dict[str, object]], needle: str) -> Optional[Dict[str, object]]:
    for r in ceil_rows:
        if needle in str(r["kind"]):
            return r
    return None


def render(verdict: Dict[str, object], bench: Dict[str, object], lives: Dict[str, object], ceilings: Dict[str, object], transfer: Optional[Dict[str, object]],
           oracle: Optional[Dict[str, object]], equiv: Dict[str, object], smoke_note: Optional[str] = None) -> str:
    m, r = verdict["marks"], verdict["readings"]
    out: List[str] = []
    out.append("# RESULT — PREREG-ACT-EFFECT (the effect screen): the bench read mechanically")
    out.append("*Generated by `tools/toys/act_effect_result.py` from the bench's JSON files; every figure below is read from them, none typed. The law is `PREREG-ACT-EFFECT.md` v2.2 (co-signed text 1d55eab).*")
    out.append("")
    out.append(f"## Verdict: **{'ADMIT' if verdict['admit'] else 'REFUSED BY THE BENCH'}**" + (" · the bench is VOID (an instrument failed: a plant not caught or a determinism check)" if verdict["void"] else ""))
    out.append("")
    out.append("| mark | reading | bar | pass |")
    out.append("|---|---|---|---|")
    m1 = m["M1"]
    out.append(f"| M1 success | C-SCR {r['c_scr_mean']:.4f} against R-NULL {r['null_mean']:.4f}: gain {m1['gain']:+.4f}; {m1['positive_seeds']}/12 seeds above; t {m1['t']:.2f}; − R-SCR {m1['minus_r_scr']:+.4f}; bar > 5 SD of null-vs-null ({r['null2_minus_null_sd']:.4f}): {m1['e']} | a ≥ +0.10 {m1['a']}; b ≥ 11/12 {m1['b']}; c t > {m1['t_crit']} {m1['c']}; d ≥ R-SCR − 0.03 {m1['d']} | {'PASS' if m1['pass'] else 'FAIL'} |")
    m2 = m["M2"]
    out.append(f"| M2 lock (two-act) | pass share {m2['pass_960']:.3f} at 960 acts, {m2['pass_full']:.3f} at {lives['acts']} | ≥ 0.95 / ≥ 0.90 | {'PASS' if m2['pass'] else 'FAIL'} |")
    m3 = m["M3"]
    out.append(f"| M3 no-ops (with M1 and M2) | share of lives ≤ 0.25: {m3['le_0.25_share']:.3f}; median no-op share {m3['median']:.3f}; alone {m3['alone']} | ≥ 0.95, jointly | {'PASS' if m3['pass'] else 'FAIL'} |")
    m4 = m["M4"]
    out.append(f"| M4 learned set | (a) no-ops judged dead ≥ 0.95 in {m4['a_share']} of lives (median {m4['a_median']}); (b) forward live ≥ 0.95 in {m4['b_share']} (median {m4['b_median']}); exact-set median {m4['exact_set_median']}; latency {m4['latency']} | each ≥ 0.90 | {'PASS' if m4['pass'] else 'FAIL'} |")
    m5 = m["M5"]["plants"]
    out.append(f"| M5 plants | P-DEAL {m5['P-DEAL']['over_null']:+.4f} over the null, no-op ≥ 0.5 in {m5['P-DEAL']['noop_ge_0.5_share']:.2f} of lives (caught {m5['P-DEAL']['caught']}); K-ARGMAX lock-pass {m5['K-ARGMAX']['pass_960']:.2f} / {m5['K-ARGMAX']['pass_full']:.2f} (caught {m5['K-ARGMAX']['caught']}); P-OLD {m5['P-OLD']['pass_960']:.2f} / {m5['P-OLD']['pass_full']:.2f} (caught {m5['P-OLD']['caught']}) | P-DEAL ≤ null + 0.02; the lock plants ≤ 0.05 | {'PASS' if m['M5']['pass'] else 'FAIL'} |")
    out.append(f"| M6 / M9 unit tests | {m['M6']['what']}; {m['M9']['what']} | green | {'PASS' if m['M6']['pass'] else 'FAIL'} |")
    m7 = m["M7"]
    out.append(f"| M7 determinism | R-NULL through the new path equals the landed rows {m7['null_equals_landed_rows']}; C-SCR twice identical {m7['candidate_twice_identical']}; R-NULL twice identical {m7['null_twice_identical']} | exact | {'PASS' if m7['pass'] else 'FAIL'} |")
    out.append(f"| M8 equivalence | {equiv.get('steps')} random steps, {equiv.get('mismatches')} mismatches (obs bytes ⟺ rendered POV sha) | 0 | {'PASS' if m['M8']['pass'] else 'FAIL'} |")
    out.append("")
    out.append("## Printed beside (never graded)")
    out.append(f"R-NULL **{r['null_mean']:.4f}** ± {r['null_sd']:.4f}; R-3 **{r['r3_mean']:.4f}** ± {r['r3_sd']:.4f} (seed-wise p95 {r['r3_seedwise_p95']:.4f}); R-SCR **{r['r_scr_mean']:.4f}**; R-CEIL **{r['ceiling_mean']:.4f}**; C-SCR **{r['c_scr_mean']:.4f}**. "
               f"C-SCR − R-NULL {r['c_scr_minus_null']:+.4f}; − R-3 {r['c_scr_minus_r3']:+.4f}; − R-SCR {r['c_scr_minus_r_scr']:+.4f}. Smallest detectable seed-level gap {r['smallest_detectable_gap_seed_level']:.4f}; null-vs-null SD {r['null2_minus_null_sd']:.4f}.")
    if oracle:
        out.append(f"R-ORACLE (BabyAIBot): success {oracle['success_mean']:.4f}, mean steps {oracle['mean_steps']:.2f}.")
    cnt = r.get("c_scr_effect_counts")
    if cnt:
        out.append("C-SCR per-act outcomes, summed over the 12 seeds (known / excluded / total): " + "; ".join(f"{a} {x['known']}/{x['excluded']}/{x['total']}" for a, x in cnt.items()) + ".")
    out.append("")
    out.append("## Ceilings re-derived from the world's own series, and where each shortfall falls")
    rows = ceilings.get("rows", [])
    iid = _row(rows, "iid")
    emps = {b: _row(rows, f"block {b}") for b in (50, 100, 200)}
    prim = emps[100]
    out.append(f"The same screen on forward's effect process: iid at the same marginal rate against block-bootstrapped from the world's recorded series (fixed random-3 play, NO candidate run); {ceilings.get('lives')} simulated lives of {ceilings.get('acts')} acts per row.")
    out.append("")
    out.append("| mark | measured | bar | iid ceiling | empirical ceiling (blocks 50 / 100 / 200) | class |")
    out.append("|---|---|---|---|---|---|")
    n_l = int(lives["n"])
    cs = lives["arms"]["C-SCR"]["summary"]
    spec = [("M2 (960 acts)", cs["h960"]["lock_pass_share"], 0.95, "m2_pass_960"), (f"M2 ({lives['acts']} acts)", cs[f"h{lives['acts']}"]["lock_pass_share"], 0.90, f"m2_pass_{lives['acts']}"),
            ("M3", cs["noop_share"]["le_0.25_share"], 0.95, "m3_pass"), ("M4(a)", cs.get("m4a_ge_0.95_share"), 0.90, "m4a_pass"), ("M4(b)", cs.get("m4b_ge_0.95_share"), 0.90, "m4b_pass")]
    for name, meas, bar, key in spec:
        if iid is None or prim is None or meas is None:
            out.append(f"| {name} | {meas} | {bar} | — | — | not priced |")
            continue
        e3 = " / ".join(f"{emps[b][key]:.3f}" if emps[b] else "—" for b in (50, 100, 200))
        out.append(f"| {name} | {meas:.3f} | {bar:.2f} | {iid[key]:.3f} | {e3} | {classify(meas, bar, iid[key], prim[key], n_l)} |")
    if iid and prim:
        out.append("")
        out.append(f"Forward's dead-time (the fraction of choices after act 300 with forward judged dead): iid {iid['forward_dead_time']:.4f}; empirical " + " / ".join(f"{emps[b]['forward_dead_time']:.4f}" for b in (50, 100, 200) if emps[b]) +
                   f" (blocks 50 / 100 / 200). Forward's share of choices: iid {iid['forward_share']:.3f}, empirical (block 100) {prim['forward_share']:.3f}.")
    out.append("")
    out.append("## The alternatives and the class-B references (printed, never admitted)")
    out.append("| arm | mean | − R-NULL | − R-3 | clears R-3's seed-wise p95 |")
    out.append("|---|---|---|---|---|")
    for k, x in verdict["alternatives"].items():
        out.append(f"| {k} | {x['mean']:.4f} | {x['minus_null']:+.4f} | {x['minus_r3']:+.4f} | {x['clears_r3_seedwise_p95']} |")
    if verdict["next_law_cases"]:
        out.append("")
        out.append("Above R-3's seed-wise p95 (the next law's cases, none built here): " + ", ".join(verdict["next_law_cases"]) + ".")
    if transfer:
        out.append("")
        out.append("## T1 — TRANSFER on BabyAI-OpenRedDoor-v0 (printed, no bar)")
        for k, a in transfer["arms"].items():
            extra = ""
            if k == "C-SCR":
                runs = a["runs"]
                extra = f"; toggle LIVE at the end on {sum(1 for x in runs if x.get('toggle_live_at_end'))}/{len(runs)} seeds"
            out.append(f"- {k}: success {a['success_mean']:.4f} ± {a['success_sd']:.4f}{extra}")
    if smoke_note:
        out.append("")
        out.append("## Disclosure")
        out.append(smoke_note)
    return "\n".join(out) + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--statusquo", required=True)
    ap.add_argument("--bench", required=True, nargs="+")
    ap.add_argument("--bench2", required=True, nargs="+")
    ap.add_argument("--lives", required=True)
    ap.add_argument("--equiv", required=True)
    ap.add_argument("--ceilings", required=True)
    ap.add_argument("--transfer")
    ap.add_argument("--oracle")
    ap.add_argument("--smoke-note")
    ap.add_argument("--unit-tests-ok", action="store_true")
    ap.add_argument("--out", required=True)
    a = ap.parse_args(list(argv) if argv is not None else None)
    load = lambda p: json.loads(Path(p).read_text())
    bench = V.merge_benches([load(p) for p in a.bench])
    v = V.verdict(load(a.statusquo), bench, V.merge_benches([load(p) for p in a.bench2]), load(a.lives), load(a.equiv), a.unit_tests_ok)
    md = render(v, bench, load(a.lives), load(a.ceilings), load(a.transfer) if a.transfer else None, load(a.oracle) if a.oracle else None, load(a.equiv), a.smoke_note)
    Path(a.out).write_text(md)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
