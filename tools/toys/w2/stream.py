"""tools/toys/w2/stream.py — PREREG-W2 §3: the bench stream over the closed record (the mentor's utterances, the states,
the dealt mirror).

edit: Kimi K3 (kimi-code, builder lane kimi-w2), 2026-10-05 02:35 +0400 — new file, written after tests/tools/test_w2_bench.py
was red; law docs/organism/whole/PREREG-W2-MENTOR-WORLD.md §3 item 2 and §5 M-CONTINGENT («SHUF: the mirror tokens dealt
to other canvases of the slice», never the names).

build(canvases, census, bench_seed): per canvas the mentor rows are generated by creature/senses/mentor.py's own rules
over the assembled canvas with `rng = substream(bench_seed, "w2:mentor:<order>")`; the referent is READ BACK from the
productions (the NP names exactly one thing, or the turn's leading hyp — presence counts printed); the utterance is the
parts {parent, carrier, mirror}; the state is state.state_of with that referent; the labels are its flags. deal_mirror:
the SHUF form — ONLY the mirror tokens are dealt (the parents' and the carriers' words stay at their canvases), the
token multiset per word preserved by the derangement's own construction.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence

import numpy as np

from brain.world.seeds import substream
from creature.senses import mentor as M
from tools.toys.w2 import state as ST
from tools.toys.w2.record import SceneCanvas

STATE_WORDS = ("unsure", "fresh", "asked")


@dataclass
class BenchStream:
    utterances: List[Dict[str, object]]          # per canvas: {parent, carrier, mirror}
    states: List[np.ndarray]
    labels: List[Dict[str, int]]
    mentor_rows: List[List[Dict[str, object]]]
    referents: List[Optional[int]]
    n_referent_readbacks: int                    # presence: canvases where the referent was read back from a production


def _readback_referent(things: Sequence[M.Thing], rows: Sequence[Dict[str, object]]) -> Optional[int]:
    """The referent the generator named, read back from the first C1/C3 production's NP: the thing matching every NP
    word, unique, else None (the turn's lead then rules the state)."""
    for prod in M.productions(rows):
        if len(prod) >= 3 and prod[0] == "alpha" and prod[1] == "sees":
            npw = prod[2:]
            cand = [i for i, t in enumerate(things) if all(M.word_true_of(w, t) for w in npw)]
            return cand[0] if len(cand) == 1 else None
    return None


def build(canvases: Sequence[SceneCanvas], census, bench_seed: int, lo: int = 0, hi: Optional[int] = None) -> BenchStream:
    """The slice [lo, hi) of the full assembly with the GLOBAL reference census (the states' young/cnt read the record's
    own counts from canvas 0; the slice bounds are positions in the full assembly)."""
    hi = len(canvases) if hi is None else min(int(hi), len(canvases))
    utterances: List[Dict[str, object]] = []
    states: List[np.ndarray] = []
    labels: List[Dict[str, int]] = []
    all_rows: List[List[Dict[str, object]]] = []
    referents: List[Optional[int]] = []
    n_rb = 0
    for pos in range(int(lo), hi):
        c = canvases[pos]
        rng = substream(bench_seed, f"w2:mentor:{c.order}")
        st = {"doubt": 0, "young": 0, "ask_prev": 0}
        rows = M.mentor_rows(M.Canvas(moment=c.moment, things=c.things, fix=c.fix, state=st,
                                      say=(c.turn.get("say") or {}).get("words") if c.turn.get("say") else None,
                                      ask_target=None, order=c.order), rng)
        ref = _readback_referent(c.things, rows)
        if ref is not None:
            n_rb += 1
        s = ST.state_of(canvases, census, pos, ref)
        prods = M.productions(rows)
        mirror = [w for w in ("unsure", "fresh", "asked") if any(p == [w] for p in prods)]
        carrier = [w for p in prods if not (len(p) == 1 and p[0] in STATE_WORDS) for w in p]
        utterances.append({"parent": list(c.words), "carrier": carrier, "mirror": mirror})
        states.append(s)
        labels.append({"doubt": int(s[0]), "young": int(s[1]), "ask_prev": int(s[2])})
        all_rows.append(rows)
        referents.append(ref)
    return BenchStream(utterances=utterances, states=states, labels=labels, mentor_rows=all_rows, referents=referents,
                       n_referent_readbacks=n_rb)


def deal_mirror(utterances: Sequence[Dict[str, object]], perm: np.ndarray) -> List[Dict[str, object]]:
    """SHUF: the mirror tokens of canvas t become those of canvas perm[t]; parents and carriers stay. The derangement's
    own construction preserves every token's total count."""
    return [{"parent": list(u["parent"]), "carrier": list(u["carrier"]),
             "mirror": list(utterances[int(perm[t])]["mirror"])} for t, u in enumerate(utterances)]


def words_of(u: Dict[str, object]) -> List[str]:
    """The canvas's full heard list, in the declared order: parent, carrier, mirror."""
    return list(u["parent"]) + list(u["carrier"]) + list(u["mirror"])
