from __future__ import annotations

import hashlib
import json
import unittest

from creature import world_maker

SEED = 20260920          # world_maker.DEFAULT_SEED -- "the value the life runs" (PREREG §2.8/§12)
WINDOWS = range(4)       # schedule(seed, w) for w in 0..3
CANVASES_PER_WINDOW = 10  # make(seed, w, i) for i in 0..9, four windows = 40 (w, i) pairs total

# Read on the UNCHANGED code (git ada2003, before this commit touches world_maker.py):
#   python3 -c "import hashlib, json; from creature import world_maker; h = hashlib.sha256()
#   ...(the exact loop below)...; print(h.hexdigest())"
WORLD_PIN_SHA256 = "bd5db2ccaa45a5a3ed80e98899e799667830c33960148945efd29689b7a897d3"


def _world_pin_hash() -> str:
    h = hashlib.sha256()
    for w in WINDOWS:
        s = world_maker.schedule(SEED, w)
        h.update(json.dumps(s).encode("utf-8"))
    for w in WINDOWS:
        for i in range(CANVASES_PER_WINDOW):
            thing, rgb, truth = world_maker.make(SEED, w, i)
            h.update(thing.encode("utf-8"))
            h.update(rgb.tobytes())
            h.update(json.dumps(truth, sort_keys=True).encode("utf-8"))
    return h.hexdigest()


class TestWorldMakerPin(unittest.TestCase):
    def test_schedule_and_make_are_byte_identical_to_the_pin(self) -> None:
        got = _world_pin_hash()
        self.assertEqual(got, WORLD_PIN_SHA256,
                          "world_maker.schedule()/make() moved for the life's own (seed, window) values -- "
                          "C1.3 must only THREAD the declared period/window through the caller, never change "
                          "what these pure functions compute")

    def test_pin_is_reproducible_within_this_process(self) -> None:
        # a control on the control: the hash must not depend on call order/caching inside this process
        self.assertEqual(_world_pin_hash(), _world_pin_hash())

    def test_default_seed_and_window_seconds_unchanged(self) -> None:
        # the pin's own precondition: if these ever move, the 40-pair hash above stops meaning what this
        # file says it means, and the literal must be re-derived on a fresh unedited checkout, not edited by hand.
        self.assertEqual(world_maker.DEFAULT_SEED, SEED)
        self.assertEqual(world_maker.WINDOW_SECONDS, 6 * 3600)


if __name__ == "__main__":
    unittest.main()
